pub struct Doc {
    pub title: &'static str,
    /// Was der Parameter bzw. die Ansicht ist und bewirkt
    pub what: &'static str,
    /// Formel (Monospace), leer = keine
    pub math: &'static str,
    /// Übliche Werte und Faustregeln
    pub typical: &'static str,
    /// Worauf man achten kann / Experiment
    pub watch: &'static str,
    pub related: &'static [Topic],
}

use Topic::*;

pub fn index() -> Vec<(&'static str, Vec<Topic>)> {
    vec![
        ("Start", vec![Welcome, Recipes, Advisor]),
        ("Daten", vec![Dataset, HfImport, TrainSize, Normalization, Augmentation]),
        ("Architektur", vec![Architecture, Dense, Conv, MaxPool, Activation, BatchNorm, Dropout, Output]),
        ("Initialisierung & Verlust", vec![Init, Loss, LabelSmoothing]),
        ("Optimierung", vec![Optimizer, Sgd, Momentum, RmsProp, Adam, LearningRate, Betas, Epsilon, WeightDecay, GradClip]),
        ("Ablauf", vec![Schedule, Warmup, Epochs, BatchSize, Threads, Seed, EvalEvery, LiveLr, SlowMo, StepMode, Throughput]),
        ("Ansichten", vec![ViewGraph, ViewLoss, ViewAcc, ViewGradNorm, ViewUpdateRatio, ViewActStats, ViewActivations, ViewWeights, ViewHistogram, ViewConfusion, ViewErrors, ViewDrawing]),
    ]
}

