/// Kommentar zur aktuellen Einstellung.
pub fn current(t: Topic, c: &TrainConfig, cores: usize) -> Option<String> {
    let adaptive = matches!(c.opt.kind, OptKind::Adam | OptKind::AdamW | OptKind::RmsProp);
    let acts: Vec<ActKind> = c.layers.iter().filter_map(|l| if let LayerSpec::Act(a) = l { Some(*a) } else { None }).collect();
    Some(match t {
        LearningRate | LiveLr => {
            let (lo, hi) = if adaptive { (1e-4, 5e-3) } else { (5e-3, 0.3) };
            let v = c.lr;
            let verdict = if v > hi * 3.0 { "deutlich zu hoch" } else if v > hi { "eher hoch" } else if v < lo / 3.0 { "sehr klein" } else if v < lo { "eher klein" } else { "im üblichen Bereich" };
            format!("Aktuell: η = {v:.2e} mit {}, {verdict}.", c.opt.kind.name())
        }
        Optimizer | Sgd | Momentum | RmsProp | Adam => format!("Aktuell: {} mit η = {:.2e}.", c.opt.kind.name(), c.lr),
        BatchSize => format!("Aktuell: Batch {} → {} Schritte pro Epoche.", c.batch, c.train_size.div_ceil(c.batch.max(1))),
        Threads => format!("Aktuell: {} von {cores} Threads.", c.threads),
        Epochs => format!("Aktuell: {} Epochen, {} Schritte insgesamt.", c.epochs, c.epochs * c.train_size.div_ceil(c.batch.max(1))),
        Init => format!("Aktuell: {}{}.", c.init.name(), if acts.iter().any(|a| matches!(a, ActKind::Sigmoid | ActKind::Tanh)) && c.init == nnlab::nn::Init::He { ", bei Sigmoid/Tanh wäre Xavier passender" } else { "" }),
        Loss => format!("Aktuell: {}.", if c.loss == LossKind::CrossEntropy { "Kreuzentropie" } else { "MSE" }),
        Schedule => format!(
            "Aktuell: {}. η reicht von {:.1e} bis {:.1e}.",
            c.schedule.name(),
            (0..=20).map(|i| c.lr_at(i as f32 / 20.0 * c.epochs as f32)).fold(f32::INFINITY, f32::min),
            (0..=20).map(|i| c.lr_at(i as f32 / 20.0 * c.epochs as f32)).fold(0.0, f32::max)
        ),
        Warmup if c.warmup_epochs > 0.0 => format!("Aktuell: {:.1} Epochen Warmup.", c.warmup_epochs),
        WeightDecay => format!("Aktuell: λ = {:.0e}{}.", c.opt.weight_decay, if c.opt.kind == OptKind::Adam && c.opt.weight_decay > 1e-3 { ", mit Adam gekoppelt. AdamW wäre besser" } else { "" }),
        Augmentation => format!("Aktuell: Verschiebung ±{} px, Spiegeln {}.", c.aug.shift, if c.aug.flip { "an" } else { "aus" }),
        Dataset | HfImport => {
            let (ch, h, w) = c.dataset.shape();
            format!(
                "Aktuell: {} ({ch}×{h}×{w}).{}",
                c.dataset.label(),
                match c.dataset.kind() {
                    DataKind::Photos => " Für Fotos sind Faltungsnetze Pflicht.",
                    DataKind::Fashion | DataKind::Glyphs => " Ein CNN bringt hier spürbar mehr als ein MLP.",
                    _ => "",
                }
            )
        }
        Activation if !acts.is_empty() => format!("Aktuell im Netz: {}.", acts.iter().map(|a| a.name()).collect::<Vec<_>>().join(", ")),
        _ => return None,
    })
}
